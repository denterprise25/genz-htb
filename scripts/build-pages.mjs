import { readFile, writeFile, mkdir, rm, lstat } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// Every route is an HTML document so refreshes and shared links work on Pages.
const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const uiRoot = join(projectRoot, 'ui');
const escapeHtml = value => String(value).replace(/[&<>"']/g, char => ({
  '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
})[char]);
const isObject = value => value !== null && typeof value === 'object' && !Array.isArray(value);
const animationKeys = new Set(['nmap', 'john', 'wireshark', 'firewall', 'vault', 'privesc', 'hashcat']);
function validateGuide(guide, label) {
  const fail = message => { throw new Error(`${label} walkthrough: ${message}`); };
  const text = (value, name) => { if (typeof value !== 'string' || !value.trim()) fail(`${name} must be nonempty text`); };
  if (guide?.generated === true) {
    text(guide.access, 'access');
    text(guide.track, 'track');
    if (!['free-documented', 'premium-documented', 'vip-included'].includes(guide.access)) fail('invalid access category');
    return;
  }
  const strings = (value, name) => { if (!Array.isArray(value) || !value.length) fail(`${name} must be a nonempty array`); value.forEach(item => text(item, name)); };
  if (!isObject(guide)) fail('must be an object');
  for (const key of ['overview', 'track', 'access']) text(guide[key], key);
  if (!['free-documented', 'premium-documented', 'vip-included'].includes(guide.access)) fail('invalid access category');
  for (const key of ['prerequisites', 'learningObjectives', 'takeaways']) strings(guide[key], key);
  if (!Array.isArray(guide.references) || !guide.references.length) fail('requires credited references');
  const refs = new Set();
  for (const ref of guide.references) {
    if (!isObject(ref)) fail('invalid reference');
    for (const key of ['id', 'title', 'author', 'url', 'type']) text(ref[key], `reference ${key}`);
    if (!/^[a-z0-9-]+$/.test(ref.id) || refs.has(ref.id)) fail('reference ids must be safe and unique');
    refs.add(ref.id);
    let url; try { url = new URL(ref.url); } catch {}
    if (!url || url.protocol !== 'https:' || url.username || url.password) fail('reference URLs must use HTTPS without credentials');
    if (!['walkthrough', 'documentation', 'platform'].includes(ref.type)) fail('invalid reference type');
  }
  if (!Array.isArray(guide.steps) || guide.steps.length < 3) fail('requires at least three learning steps');
  const ids = new Set();
  for (const step of guide.steps) {
    if (!isObject(step)) fail('invalid step');
    for (const key of ['id', 'title', 'explanation']) text(step[key], `step ${key}`);
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(step.id) || ids.has(step.id)) fail('step ids must be safe and unique');
    ids.add(step.id);
    if (!Array.isArray(step.commands)) fail('step commands must be an array');
    for (const cmd of step.commands) {
      if (!isObject(cmd)) fail('invalid command');
      for (const key of ['label', 'runOn', 'code', 'why', 'expect']) text(cmd[key], `command ${key}`);
    }
    strings(step.checks, 'step checks');
    strings(step.sourceIds, 'step sourceIds');
    if (step.sourceIds.some(id => !refs.has(id))) fail('step cites an unknown reference');
    if (step.animation && !animationKeys.has(step.animation)) fail('unknown step animation');
  }
  if (!Array.isArray(guide.troubleshooting) || !guide.troubleshooting.length) fail('requires troubleshooting');
  for (const item of guide.troubleshooting) {
    if (!isObject(item)) fail('invalid troubleshooting item');
    text(item.problem, 'troubleshooting problem'); text(item.solution, 'troubleshooting solution');
  }
}
// Parse a quoted JSON string rather than treating content as JavaScript object
// syntax. Escaping HTML delimiters also makes the bundle safe to inline later.
const bundleSource = value => '// Generated by scripts/build-pages.mjs. Edit ui/data/*.json instead.\n' +
  'window.GenzSiteData = JSON.parse(' + JSON.stringify(JSON.stringify(value))
    .replace(/[<>&\u2028\u2029]/g, character => '\\u' + character.charCodeAt(0).toString(16).padStart(4, '0')) + ');\n';

async function readData(name, optional = false) {
  try {
    return JSON.parse(await readFile(join(uiRoot, 'data', name), 'utf8'));
  } catch (error) {
    if (optional && error.code === 'ENOENT') return {};
    throw new Error(`${name}: ${error.message}`);
  }
}

async function build() {
  const template = await readFile(join(uiRoot, 'index.html'), 'utf8');
  const records = await readData('machines.json');
  const learningNotes = await readData('learning-notes.json');
  const visualContexts = await readData('visual-contexts.json', true);
  if (!Array.isArray(records)) {
    throw new Error('machines.json must contain an array of machine records (an empty array is allowed).');
  }
  const heads = [...template.matchAll(/<head\b[^>]*>[\s\S]*?<\/head>/gi)];
  if (heads.length !== 1) throw new Error('ui/index.html must have exactly one head element.');
  const head = heads[0][0];
  // SVG illustrations have their own accessible titles; document metadata
  // belongs to the HTML head and must be validated independently.
  for (const [name, pattern, source] of [
    ['base href="./"', /<base\s+href=["']\.\/["']\s*\/?\s*>/gi, head],
    ['body data-page="home"', /<body\b[^>]*\bdata-page=["']home["'][^>]*>/gi, template],
    ['title', /<title\b[^>]*>[\s\S]*?<\/title>/gi, head],
    ['description', /<meta\b(?=[^>]*\bname=["']description["'])[^>]*>/gi, head],
  ]) {
    if ([...source.matchAll(pattern)].length !== 1) {
      throw new Error(`ui/index.html must have exactly one ${name} element.`);
    }
  }

  const ids = new Set();
  const slugs = new Set();
  const pages = [
    { path: ['machines'], page: 'catalog', title: 'All machine walkthroughs — Gen Z HTB',
      description: 'Browse Hack The Box machines and TryHackMe rooms by platform, operating system, difficulty, and technique.' },
    { path: ['hack-the-box'], page: 'htb', title: 'Hack The Box walkthroughs — Gen Z HTB',
      description: 'Explore Hack The Box machine walkthroughs, from enumeration and initial access to privilege escalation and the reasoning behind each step.' },
    { path: ['tryhackme'], page: 'thm', title: 'TryHackMe room walkthroughs — Gen Z HTB',
      description: 'Explore TryHackMe room walkthroughs with clear learning goals, difficulty details, and credited guides.' },
  ];

  records.forEach((record, index) => {
    const label = `Machine record ${index + 1}`;
    if (!record || typeof record !== 'object' || Array.isArray(record)) {
      throw new Error(`${label} must be an object.`);
    }
    for (const field of ['id', 'slug', 'title', 'platform', 'os', 'difficulty', 'summary', 'content']) {
      if (typeof record[field] !== 'string' || !record[field].trim()) {
        throw new Error(`${label} requires a nonempty ${field} string.`);
      }
    }
    if (!['Hack The Box', 'TryHackMe'].includes(record.platform)) {
      throw new Error(`${label} has an unsupported platform: ${record.platform}`);
    }
    if (ids.has(record.id)) throw new Error(`Duplicate machine id: ${record.id}`);
    ids.add(record.id);
    const slug = record.slug;
    if (typeof slug !== 'string' || slug.length > 100 || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug)) {
      throw new Error(`${label} has an unsafe slug: ${String(slug)}`);
    }
    if (slugs.has(slug)) throw new Error(`Duplicate machine slug: ${slug}`);
    slugs.add(slug);
    if (record.sourceUrl) {
      let source;
      try { source = new URL(record.sourceUrl); } catch { /* Rejected below. */ }
      if (!source || source.protocol !== 'https:' || source.username || source.password) {
        throw new Error(`${label} sourceUrl must be an absolute HTTPS URL without credentials.`);
      }
    }
    if (record.guide) validateGuide(record.guide, label);
    pages.push({ path: ['machines', slug], page: 'detail', machine: slug,
      title: `${record.title} · ${record.platform} walkthrough — Gen Z HTB`,
      description: record.summary });
  });

  if (!isObject(learningNotes)) throw new Error('learning-notes.json must be an object keyed by machine slug.');
  for (const [slug, note] of Object.entries(learningNotes)) {
    if (!slugs.has(slug)) throw new Error(`Learning note references an unknown machine: ${slug}`);
    if (!isObject(note) || ['notice', 'reason'].some(field => typeof note[field] !== 'string' || !note[field].trim())) {
      throw new Error(`Learning note ${slug} requires nonempty notice and reason strings.`);
    }
  }
  if (!isObject(visualContexts)) throw new Error('visual-contexts.json must be an object.');
  const concepts = new Set(['nmap', 'john', 'wireshark', 'firewall', 'vault', 'privesc', 'hashcat']);
  const machineTopics = new Map(records.map(record => [record.slug, new Set(String(record.tags || '').split(',').map(tag => tag.trim()))]));
  for (const [slug, contexts] of Object.entries(visualContexts)) {
    if (!slugs.has(slug)) throw new Error(`Visual context references an unknown machine: ${slug}`);
    if (!Array.isArray(contexts)) throw new Error(`Visual contexts for ${slug} must be an array.`);
    const used = new Set();
    for (const context of contexts) {
      if (!isObject(context) || ['concept', 'topic', 'title', 'context', 'why', 'relation'].some(field =>
        typeof context[field] !== 'string' || !context[field].trim())) {
        throw new Error(`Visual contexts for ${slug} require nonempty concept, topic, title, context, why, and relation strings.`);
      }
      if (!concepts.has(context.concept)) throw new Error(`Unknown animation concept for ${slug}: ${context.concept}`);
      if (!machineTopics.get(slug).has(context.topic)) throw new Error(`Visual context ${slug}/${context.concept} must reference one of the machine's listed topics.`);
      if (used.has(context.concept)) throw new Error(`Duplicate ${context.concept} animation for ${slug}.`);
      used.add(context.concept);
      if (!['guide', 'background'].includes(context.relation)) {
        throw new Error(`Visual context ${slug}/${context.concept} must have a guide or background relation.`);
      }
    }
  }
  const dataBundle = bundleSource({ machines: records, learningNotes, visualContexts });

  // Validate all input before replacing generated directories. Reject symlinks
  // rather than following an unexpected route directory outside the project.
  const routes = ['machines', 'hack-the-box', 'tryhackme'];
  for (const route of routes) {
    const target = join(uiRoot, route);
    const stat = await lstat(target).catch(error => {
      if (error.code === 'ENOENT') return null;
      throw error;
    });
    if (stat && (!stat.isDirectory() || stat.isSymbolicLink())) {
      throw new Error(`Generated route must be a directory, not a file or symlink: ${target}`);
    }
  }
  await import('./build-concept-assets.mjs');
  for (const route of routes) await rm(join(uiRoot, route), { recursive: true, force: true });
  await writeFile(join(uiRoot, 'data', 'site-data.js'), dataBundle);

  for (const page of pages) {
    const bodyAttributes = ` data-page="${page.page}"${page.machine ? ` data-machine="${page.machine}"` : ''}`;
    const pageHead = head
      .replace(/<base\s+href=["']\.\/["']\s*\/?\s*>/i, `<base href="${'../'.repeat(page.path.length)}">`)
      .replace(/<title\b[^>]*>[\s\S]*?<\/title>/i, () => `<title>${escapeHtml(page.title)}</title>`)
      .replace(/<meta\b(?=[^>]*\bname=["']description["'])[^>]*>/i,
        () => `<meta name="description" content="${escapeHtml(page.description)}">`);
    const html = template.replace(head, () => pageHead)
      .replace(/<body\b[^>]*>/i, tag => tag.replace(/\s+data-(?:page|machine)=["'][^"']*["']/gi, '')
        .replace(/>$/, `${bodyAttributes}>`));
    const output = join(uiRoot, ...page.path);
    await mkdir(output, { recursive: true });
    await writeFile(join(output, 'index.html'), html);
  }
  console.log(`Built ${pages.length} static routes and the local data bundle for ${records.length} machines.`);
}

build().catch(error => {
  console.error(`Pages build failed: ${error.message}`);
  process.exitCode = 1;
});
