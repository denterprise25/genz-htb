import { readFile, writeFile } from 'node:fs/promises';

// The committed bundle is a classic script so local file previews need no fetch.
// Each render replaces __GC__ with a unique instance name, including SVG ids,
// classes and keyframes. Multiple copies of one concept therefore stay separate.
const keys = ['nmap', 'john', 'wireshark', 'firewall', 'vault', 'privesc', 'hashcat'];
const escapeRegExp = value => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

function prepare(source, key) {
  if (/<script\b|\bon\w+\s*=|(?:href|src)=["']https?:/i.test(source)) {
    throw new Error(`${key}: SVG must contain only local, declarative artwork.`);
  }
  const ids = [...source.matchAll(/\bid="([^"]+)"/g)].map(match => match[1]);
  if (new Set(ids).size !== ids.length) throw new Error(`${key}: duplicate source ids.`);
  const classes = new Set([...source.matchAll(/\bclass="([^"]+)"/g)].flatMap(match => match[1].split(/\s+/)));

  source = source.replace(/<style>([\s\S]*?)<\/style>/g, (_, original) => {
    let css = original;
    const animations = [...css.matchAll(/@keyframes\s+([\w-]+)/g)].map(match => match[1]);
    css = css.replace(/(@keyframes\s+)([\w-]+)/g, '$1__GC__-$2');
    css = css.replace(/(animation(?:-name)?\s*:\s*)([^;}]+)/g, (_, property, value) => {
      for (const name of animations) value = value.replace(new RegExp(`\\b${escapeRegExp(name)}\\b`, 'g'), `__GC__-${name}`);
      return property + value;
    });
    // The checkpoint source originally used bare state selectors.
    if (key === 'firewall') css = css.replace(/\[data-(step|playing)=/g, '.__GC__[data-$1=');
    css = css.replace(/\.(?:ct|cm|ca)-product\b/g, '.__GC__');
    css = css.replace(/\.([A-Za-z_][\w-]*)/g, (selector, name) => classes.has(name) ? `.__GC__-${name}` : selector);
    return `<style>${css}</style>`;
  });
  source = source.replace(/\bclass="([^"]+)"/g, (_, value) => `class="${value.split(/\s+/).map(name => `__GC__-${name}`).join(' ')}"`);
  source = source.replace(/\bid="([^"]+)"/g, 'id="__GC__-$1"');
  source = source.replace(/\b(aria-labelledby|aria-describedby)="([^"]+)"/g, (_, name, value) => `${name}="${value.split(/\s+/).map(id => `__GC__-${id}`).join(' ')}"`);
  for (const id of ids) source = source.replace(new RegExp(`#${escapeRegExp(id)}(?=["')\\s])`, 'g'), `#__GC__-${id}`);
  source = source.replace(/--(?:ct|cm|ca)-/g, '--gc-');
  source = source.replace(/<!--([\s\S]*?)-->/g, '').trim();
  if (/\.(?:ct|cm|ca)-|--(?:ct|cm|ca)-/.test(source)) throw new Error(`${key}: unscoped source remains.`);
  return source;
}

const assets = {};
for (const key of keys) {
  const source = await readFile(new URL(`./concept-sources/${key}.svg`, import.meta.url), 'utf8');
  assets[key] = prepare(source, key);
}
const output = `// Generated by scripts/build-concept-assets.mjs. Edit scripts/concept-sources instead.\nwindow.GenzConceptAssets = Object.freeze(${JSON.stringify(assets, null, 2)});\n`;
await writeFile(new URL('../ui/concept-assets.js', import.meta.url), output);
console.log(`Prepared ${keys.length} independently scoped concept animations.`);
