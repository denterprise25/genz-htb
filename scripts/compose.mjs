import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
let html=fs.readFileSync(path.join(root,'ui/index.html'),'utf8');
const fonts=fs.readFileSync(path.join(root,'ui/fonts/fonts.css'),'utf8').replace(/url\(([^)]+)\)/g,(_,name)=>'url(data:font/ttf;base64,'+fs.readFileSync(path.join(root,'ui/fonts',name)).toString('base64')+')');
html=html.replace('/* FONTS */',fonts);
const server=fs.readFileSync(path.join(root,'worker/server.js'),'utf8');
fs.writeFileSync(path.join(root,'worker/index.js'),'// Generated by scripts/compose.mjs from ui/index.html and worker/server.js.\nconst PAGE = '+JSON.stringify(html)+';\n'+server);
console.log('Composed the Rootnotes UI and server.');
